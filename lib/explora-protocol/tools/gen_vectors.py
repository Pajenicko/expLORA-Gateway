#!/usr/bin/env python3
# expLORA protocol generation 2 - independent reference implementation that
# produces the frame test vectors (test/test_protocol_v2/vectors.h).
# Uses the "cryptography" package for AES and CMAC, nothing from the C++ code.
#   python3 lib/explora-protocol/tools/gen_vectors.py > test/test_protocol_v2/vectors.h
import struct
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.cmac import CMAC

VERSION = 1
JOIN_REQ, JOIN_ACC, UP, DOWN = 0, 1, 2, 3
CODE = {"joinreq": 0x00, "joinacc": 0x01, "up": 0x02, "down": 0x03, "rejoin": 0x11}


def aes(key, block):
    e = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    return e.update(block) + e.finalize()


def cmac(key, msg):
    c = CMAC(algorithms.AES(key))
    c.update(msg)
    return c.finalize()


def u32(v):
    return struct.pack(">I", v)


def mhdr(t):
    return bytes([0xA0 | (t << 3) | VERSION])


def ctr(key, dirn, code, dev, counter, data):
    out = bytearray()
    for i in range(0, len(data), 16):
        a = bytes([0x01, dirn, code]) + u32(dev) + u32(counter) + b"\0\0\0\0" + bytes([i // 16 + 1])
        ks = aes(key, a)
        out += bytes(x ^ y for x, y in zip(data[i:i + 16], ks))
    return bytes(out)


def mic(key, dirn, code, dev, counter, bind, msg):
    b0 = bytes([0x49, dirn, code]) + u32(dev) + u32(counter) + u32(bind) + bytes([len(msg)])
    return cmac(key, b0 + msg)[:4]


def tlv(t, value, channel=0):
    out = bytes([t | (0x20 if channel else 0)])
    if channel:
        out += bytes([channel])
    if t >> 6 == 3:
        out += bytes([len(value)])
    return out + value


# Inputs
LABEL = bytes.fromhex("A1B2C3D4E5F60718")  # printed as A1B2-C3D4-E5F6-0718
DEVID = 0x3EA4191D
DEVNONCE = 7
GWNONCE = 0x11223344

K = cmac(LABEL + b"\0" * 8, u32(DEVID))
KJ_ENC = cmac(K, b"\x02" + u32(DEVID))
KJ_MIC = cmac(K, b"\x04" + u32(DEVID))
nonces = u32(DEVNONCE) + u32(GWNONCE)
KS_ENC = cmac(K, b"\x01" + u32(DEVID) + nonces)
KS_MIC = cmac(K, b"\x03" + u32(DEVID) + nonces)

# JOIN_REQ: hw 0x0003, fw 0.1.0, caps RX2, config version 0
jr = mhdr(JOIN_REQ) + u32(DEVID) + b"JR" + u32(DEVNONCE) + struct.pack(">H", 3) + bytes([0, 1, 0, 0x02, 0])
jr += mic(KJ_MIC, 0, CODE["joinreq"], DEVID, DEVNONCE, 0, jr)

# JOIN_ACC ACCEPT: config version 1, interval 600 s / slot 123 s, TX power 14, time
acc_tlv = tlv(0x81, struct.pack(">HH", 600, 123)) + tlv(0x01, bytes([14])) + tlv(0x82, u32(1792265000))
body = u32(GWNONCE) + bytes([1]) + acc_tlv
ja = mhdr(JOIN_ACC) + u32(DEVID) + b"\x00" + ctr(KJ_ENC, 1, CODE["joinacc"], DEVID, DEVNONCE, body)
ja += mic(KJ_MIC, 1, CODE["joinacc"], DEVID, DEVNONCE, 0, ja)

# UP FCnt 5, ACK requested, config version 1: temperature 21.40, RH 59.56, battery 3090 mV,
# second temperature on channel 2 (invalid), board data
up_tlv = (tlv(0x41, struct.pack(">h", 2140)) + tlv(0x42, struct.pack(">H", 5956)) + tlv(0x46, struct.pack(">H", 3090))
          + tlv(0x41, struct.pack(">h", -32768), channel=2) + tlv(0xC0, b"\xde\xad\xbe"))
UP_FCNT = 5
up = mhdr(UP) + u32(DEVID) + struct.pack(">H", UP_FCNT) + bytes([0x81]) + ctr(KS_ENC, 0, CODE["up"], DEVID, UP_FCNT, up_tlv)
up += mic(KS_MIC, 0, CODE["up"], DEVID, UP_FCNT, 0, up)

# DOWN FCnt 0x10002 (low 16 bits 0x0002), ACK of the UP above, gateway config version 1, time
DN_FCNT = 0x10002
dn_tlv = tlv(0x82, u32(1792265600))
dn = mhdr(DOWN) + u32(DEVID) + struct.pack(">H", DN_FCNT & 0xFFFF) + bytes([0x81]) + ctr(KS_ENC, 1, CODE["down"], DEVID, DN_FCNT, dn_tlv)
dn += mic(KS_MIC, 1, CODE["down"], DEVID, DN_FCNT, UP_FCNT, dn)

# REJOIN answering the UP above (FCnt16 + MIC of that uplink)
rj = mhdr(JOIN_ACC) + u32(DEVID) + b"\x01"
rj += mic(KJ_MIC, 1, CODE["rejoin"], DEVID, UP_FCNT, struct.unpack(">I", up[-4:])[0], rj)


def arr(name, data):
    body = ", ".join("0x%02x" % b for b in data)
    return "static const uint8_t %s[%d] = {%s};" % (name, len(data), body)


out = [
    "// Generated by lib/explora-protocol/tools/gen_vectors.py (independent Python",
    "// reference using the cryptography package) - do not edit.",
    "#pragma once",
    "#include <cstdint>",
    "",
    "static const char *const kVecLabelText = \"A1B2-C3D4-E5F6-0718\";",
    "static const uint32_t kVecDevId = 0x%08X;" % DEVID,
    "static const uint32_t kVecDevNonce = %d;" % DEVNONCE,
    "static const uint32_t kVecGwNonce = 0x%08X;" % GWNONCE,
    "static const uint32_t kVecUpFcnt = %d;" % UP_FCNT,
    "static const uint32_t kVecDownFcnt = 0x%X;" % DN_FCNT,
    arr("kVecRootKey", K), arr("kVecJoinEnc", KJ_ENC), arr("kVecJoinMic", KJ_MIC),
    arr("kVecSessEnc", KS_ENC), arr("kVecSessMic", KS_MIC),
    arr("kVecJoinReq", jr), arr("kVecJoinAccTlv", acc_tlv), arr("kVecJoinAcc", ja),
    arr("kVecUpTlv", up_tlv), arr("kVecUp", up), arr("kVecDownTlv", dn_tlv), arr("kVecDown", dn),
    arr("kVecRejoin", rj),
    "",
]
sys.stdout.write("\n".join(out))
