#!/usr/bin/env python3
"""
Generates fixtures.h for test_manifest with the release tools
(tools/release): synthetic gateway (Pro 2.1.3, Lite 2.1.4) and sensor
(HW 0x0003 0.2.12, HW 0x0004 0.3.1) images signed through explora_sign.py
and manifests made by explora_manifest.py with a throwaway TEST key, plus
a few hand-made bodies signed the same way (CRLF, extra fields, a field
the gateway skips) and a manifest signed by a second key the test table
does not carry. The rule corpus (CORPUS) holds unsigned JSON bodies with
the verdict of explora_manifest.check_json for each: the native test parses
them with the firmware's limits and checks the gateway agrees entry by
entry (the tool mirrors the gateway's rules).

The private keys exist only in a temporary folder during the run and are
deleted afterwards; fixtures.h holds the public point, the signed images
and the manifests only. Re-running creates new keys and new fixtures.

  python3 test/test_manifest/gen_fixtures.py
"""

import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(HERE, "..", "..", "tools", "release")
sys.path.insert(0, TOOLS)
sys.path.insert(0, os.path.join(HERE, "..", "test_sigverify"))
import explora_sigblock as sb  # noqa: E402
import explora_manifest as em  # noqa: E402
from gen_fixtures import gateway_image, sensor_image, write_key, c_array  # noqa: E402

BASE = "https://example.com/explora/v2"


def tool(*args):
    r = subprocess.run([sys.executable] + list(args), capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    return r


def main():
    with tempfile.TemporaryDirectory() as tmp:
        ka, kb = os.path.join(tmp, "a.pem"), os.path.join(tmp, "b.pem")
        key_a, key_b = write_key(ka), write_key(kb)
        files = {}
        for name, kind, data in (
            ("gw-pro-2.1.3.bin", "gateway", gateway_image(b"2.1.3", chip=0)),
            ("gw-lite-2.1.4.bin", "gateway", gateway_image(b"2.1.4", chip=9)),
            ("hw0003-0.2.12.bin", "sensor", sensor_image(0x0003, 0x00020C, size=512)),
            ("hw0004-0.3.1.bin", "sensor", sensor_image(0x0004, 0x000301, size=640)),
        ):
            src, dst = os.path.join(tmp, "raw-" + name), os.path.join(tmp, name)
            with open(src, "wb") as f:
                f.write(data)
            tool(os.path.join(TOOLS, "explora_sign.py"), "sign", "--kind", kind, "--key", ka, src, dst)
            with open(dst, "rb") as f:
                files[name] = f.read()
        signed = [os.path.join(tmp, n) for n in files]
        mf = os.path.join(TOOLS, "explora_manifest.py")
        good, seq6, other = (os.path.join(tmp, n) for n in ("good.json", "seq6.json", "other.json"))
        tool(mf, "build", "--base", BASE, "--seq", "5", "--key", ka, "-o", good, *signed)
        tool(mf, "build", "--base", BASE, "--seq", "auto", "--prev", good, "--key", ka, "-o", seq6, *signed)
        # Key B signs files signed by key A: allowed with --pub A
        tool(mf, "build", "--base", BASE, "--seq", "9", "--key", kb, "--pub", ka + ".pub", "-o", other, *signed)
        man = {}
        for n, p in (("good", good), ("seq6", seq6), ("other", other)):
            with open(p, "rb") as f:
                man[n] = f.read()
        doc = json.loads(man["good"].split(b"\n", 1)[1])
        # Hand-made bodies signed by key A
        crlf = dict(doc, note="extra top-level key", issued=-5)
        crlf["gateway"] = {"lite": dict(doc["gateway"]["lite"], channel="beta")}  # no "pro"
        crlf["sensor"] = {"0003": dict(doc["sensor"]["0003"], notes={"a": [1, 2, 3]})}
        crlf_body = json.dumps(crlf, indent=1).replace("\n", "\r\n").encode() + b"\r\n"
        bad = json.loads(json.dumps(doc))
        bad["sensor"]["0004"]["sha256"] = bad["sensor"]["0004"]["sha256"].upper()
        bad_body = em.body_of(bad)
        noseq = {k: v for k, v in doc.items() if k != "seq"}
        man["crlf"] = em.sign_body(key_a, crlf_body)
        man["badfield"] = em.sign_body(key_a, bad_body)
        man["noseq"] = em.sign_body(key_a, em.body_of(noseq))
        pa = sb.public_point(key_a.public_key())
        ida, idb = sb.key_id(key_a.public_key()), sb.key_id(key_b.public_key())

    cases = corpus(doc)
    text = (
        "// Generated by gen_fixtures.py - do not edit. TEST keys only (private\n"
        "// parts were discarded); never a release key.\n#pragma once\n#include <cstdint>\n\n"
        f"static const uint32_t TEST_KEY_ID = 0x{ida:08X}u;\n"
        f"static const uint32_t OTHER_KEY_ID = 0x{idb:08X}u; // not in the test table\n"
        + c_array("TEST_KEY_POINT", pa)
        + "// Signed images (key A): Pro 2.1.3, Lite 2.1.4, HW3 0.2.12, HW4 0.3.1\n"
        + c_array("GW_PRO", files["gw-pro-2.1.3.bin"]) + c_array("GW_LITE", files["gw-lite-2.1.4.bin"])
        + c_array("HW3_IMG", files["hw0003-0.2.12.bin"]) + c_array("HW4_IMG", files["hw0004-0.3.1.bin"])
        + "// explora_manifest.py build --seq 5 (all four files)\n" + c_array("M_GOOD", man["good"])
        + "// --seq auto --prev M_GOOD (seq 6)\n" + c_array("M_SEQ6", man["seq6"])
        + "// signed by key B (seq 9)\n" + c_array("M_OTHER", man["other"])
        + "// hand-made: CRLF pretty JSON, extra keys, only the Lite board, HW3 only\n"
        + c_array("M_CRLF", man["crlf"])
        + "// hand-made: sensor 0004 sha256 in uppercase\n" + c_array("M_BADFIELD", man["badfield"])
        + "// hand-made: no seq\n" + c_array("M_NOSEQ", man["noseq"])
        + corpus_text(cases)
    )
    with open(os.path.join(HERE, "fixtures.h"), "w") as f:
        f.write(text)
    print("fixtures.h written")


SHA = "0123456789abcdef" * 4


def pkg(version="2.0.1", url="https://h.example/f.bin", size=100000, **extra):
    p = {"version": version, "url": url, "size": size, "sha256": SHA}
    p.update(extra)
    return p


def body(doc, trailer=""):
    return (json.dumps(doc, separators=(",", ":"), ensure_ascii=False) + trailer).encode()


def corpus(good):
    """(name, JSON body bytes) - each one a rule case of check_json."""
    out = [("tool manifest", body(good)),
           ("crlf pretty + trailing bytes", (json.dumps(good, indent=2).replace("\n", "\r\n") + "\r\n junk").encode())]

    def gw(p, board="pro", **top):
        d = {"seq": 7, "gateway": {board: p}}
        d.update(top)
        return d

    def sn(p, key="0003"):
        return {"seq": 7, "sensor": {key: p}}

    urls = {
        "userinfo": "https://user@h.example/f.bin",
        "user pass port": "https://u:p@h.example:8443/f.bin",
        "two @": "https://a@b@h.example/f.bin",
        "@ in password": "https://u:p@ss@h.example/f.bin",
        "host 127 B": "https://" + "h" * 127 + "/f",
        "host 128 B": "https://" + "h" * 128 + "/f",
        "url 256 B": "https://h.example/" + "a" * (256 - 18),
        "url 257 B": "https://h.example/" + "a" * (257 - 18),
        "url 256 chars 257 bytes": "https://h.example/" + "a" * 237 + "\u00e9",
        "ipv6 literal": "https://[::1]:8443/f.bin",
        "lone bracket": "https://[/f",
        "query in host": "https://h.example?x/f",
        "query after port": "https://h.example:80?x/f",
        "hash in host": "https://h#x/f",
        "no host": "https:///f.bin",
        "port only": "https://:443/f.bin",
        "http": "http://h.example/f.bin",
        "space": "https://h.example/a b.bin",
        "tab": "https://h.example/a\tb.bin",
        "del": "https://h.example/a\x7fb.bin",
        "utf8 path": "https://h.example/\u017elu\u0165ou\u010dk\u00fd.bin",
        "no path": "https://h.example",
    }
    for name, u in urls.items():
        out.append(("url " + name, body(gw(pkg(url=u)))))
        out.append(("sensor url " + name, body(sn(pkg(url=u, size=4096)))))
    for v in ["2.0.1", "002.000.001", "0.0.0", "255.255.255", "2.0.256", "2.0", "2.0.0-dev", " 2.0.0", "2..0",
              "2.0.0.", "+2.0.0", "1e1.0.0", "\uff11.2.3"]:
        out.append(("version " + v, body(gw(pkg(version=v)))))
    for size in [152, 153, 4194304, 4194305, 0, -1, 1.0, "1000", True, 2 ** 32]:
        out.append(("gateway size %r" % (size,), body(gw(pkg(size=size)))))
        out.append(("lite size %r" % (size,), body(gw(pkg(size=size), board="lite"))))
    for size in [511, 512, 114816, 114817, 100000]:
        out.append(("sensor size %r" % (size,), body(sn(pkg(size=size)))))
    for sha in [SHA.upper(), SHA[:-1], SHA + "0", "g" + SHA[1:], None, 5]:
        p = pkg()
        p["sha256"] = sha
        out.append(("sha %r" % (sha,), body(gw(p))))
    missing = pkg()
    del missing["url"]
    out.append(("missing url", body(gw(missing))))
    out.append(("package not an object", body(gw(5))))
    out.append(("package array", body(gw([1]))))
    out.append(("board null", body(gw(None))))
    out.append(("gateway null", body({"seq": 1, "gateway": None, "sensor": None})))
    out.append(("both boards, lite invalid", body({"seq": 1, "gateway": {"pro": pkg(), "lite": pkg(version="x")}})))
    out.append(("both boards, pro invalid", body({"seq": 1, "gateway": {"pro": pkg(url="x"), "lite": pkg()}})))
    out.append(("unknown board", body({"seq": 1, "gateway": {"esp32c6": {"anything": [1, 2]}, "pro": pkg()}})))
    for key in ["0003", "00A3", "FFFF", "00a3", "0000", "3", "00003", "0x03", "", "00G3"]:
        out.append(("sensor key %r" % key, body(sn(pkg(size=4096), key=key))))
    nine = {"seq": 2, "sensor": {"%04X" % i: pkg(size=4096) for i in range(1, 10)}}
    out.append(("nine sensors", body(nine)))
    bad_first = {"seq": 2, "sensor": {"%04X" % i: pkg(size=4096 if i != 2 else 5) for i in range(1, 10)}}
    out.append(("nine sensors, second invalid", body(bad_first)))
    twelve = {"seq": 2, "sensor": {"%04X" % i: pkg(size=4096, url="https://h/%d" % i) for i in range(1, 13)}}
    out.append(("twelve sensors", body(twelve)))
    big = {"seq": 3, "gateway": {"pro": pkg(size=5 * 1024 * 1024), "lite": pkg()},
           "sensor": {"0003": pkg(size=200000), "0004": pkg(size=4096, channel="beta", min_gw="2.1.0"),
                      "0010": pkg(version="0.300.1", size=4096)}}
    out.append(("future release", body(big)))
    out.append(("extra fields everywhere",
                body({"seq": 1, "issued": "x", "notes": {"a": [1, {"b": None}]},
                      "gateway": {"pro": pkg(beta=True, notes="n"), "x": 1},
                      "sensor": {"0003": pkg(size=4096, hw="3", flags=[1, 2])}})))
    for seq in [0, 4294967295, 4294967296, -1, 1.5, "5", None, True]:
        d = {"gateway": {"pro": pkg()}}
        if seq is not None:
            d["seq"] = seq
        out.append(("seq %r" % (seq,), body(d)))
    out.append(("no seq", body({"gateway": {"pro": pkg()}})))
    out.append(("gateway array", body({"seq": 1, "gateway": [], "sensor": {"0003": pkg(size=4096)}})))
    out.append(("sensor string", body({"seq": 1, "sensor": "x"})))
    out.append(("root array", b"[1]"))
    # Node and depth bounds: 384 values (distinct strings, the worst case
    # for the gateway's string pool) parse; nesting 10 deep parses, 11 not
    words = ["w%05d" % i for i in range(382)]
    out.append(("384 values", body({"seq": 1, "x": words})))
    out.append(("depth 10", body({"seq": 1, "x": [[[[[[[[[]]]]]]]]]})))
    out.append(("depth 11", body({"seq": 1, "x": [[[[[[[[[[]]]]]]]]]]})))
    return out


def corpus_text(cases):
    """The cases with check_json's verdict per entry: refused, the sensor
    packages kept, each board's entry (1 valid, 0 skipped, -1 absent) and
    the number of skipped entries."""
    rows, blobs = [], []
    for i, (name, data) in enumerate(cases):
        assert len(data) <= em.MAX_FILE - 144, name
        doc = em.parse_body(data)  # the corpus holds only JSON both read alike
        refusals, skips = em.check_json(doc)
        boards = []
        for b in ("pro", "lite"):
            p = (doc.get("gateway") or {}).get(b) if isinstance(doc, dict) and isinstance(doc.get("gateway"), dict) \
                else None
            boards.append(-1 if p is None else (0 if any(s.startswith(f"gateway.{b}") for s in skips) else 1))
        kept = 0
        if not refusals and isinstance(doc.get("sensor"), dict):
            kept = len(doc["sensor"]) - sum(1 for s in skips if s.startswith("sensor."))
        blobs.append(c_array(f"CORPUS_{i}", data))
        rows.append(f"    {{{json.dumps(name)}, CORPUS_{i}, sizeof(CORPUS_{i}), {int(bool(refusals))}, {kept}, "
                    f"{boards[0]}, {boards[1]}, {len(skips)}}},")
    return ("\n// Rule corpus: JSON bodies and explora_manifest.check_json's verdict\n"
            + f"static const uint32_t PY_GATEWAY_MIN = {em.GATEWAY_MIN}u, PY_GATEWAY_MAX = {em.GATEWAY_MAX}u;\n"
            + f"static const uint32_t PY_SENSOR_MIN = {em.SENSOR_MIN}u, PY_SENSOR_MAX = {em.SENSOR_MAX}u;\n"
            + f"static const unsigned PY_MAX_NODES = {em.MAX_NODES}u, PY_MAX_SENSORS = {em.MAX_SENSORS}u;\n"
            + "".join(blobs)
            + "struct CorpusCase\n{\n    const char *name;\n    const uint8_t *data;\n    size_t len;\n"
            "    int refused, sensorsKept, pro, lite, skips;\n};\nstatic const CorpusCase CORPUS[] = {\n"
            + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    main()
