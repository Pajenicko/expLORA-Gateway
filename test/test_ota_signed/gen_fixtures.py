#!/usr/bin/env python3
"""
Generates fixtures.h for test_ota_signed: a synthetic sensor image (HW
0x0003, 0.2.12, 1024 B incl. the trailer) signed through explora_sign.py
with a throwaway TEST key, and signature blocks for the refusal cases
(wrong HW type / version / kind / length / content, a bad signature that
claims the test key's id, a block signed by a second key that the gateway
does not know).

Both private keys exist only in a temporary folder during the run and are
deleted afterwards; fixtures.h holds the public points, the image and the
blocks only. Re-running creates new keys and new fixtures.

  python3 test/test_ota_signed/gen_fixtures.py
"""

import os
import struct
import subprocess
import sys
import tempfile
import zlib

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(HERE, "..", "..", "tools", "release")
sys.path.insert(0, TOOLS)
import explora_sigblock as sb  # noqa: E402

HW = 0x0003
FW = 0 << 16 | 2 << 8 | 12


def sensor_image(hw=HW, fw=FW, size=1024):
    img = bytearray(size)
    for i in range(size - 32):
        img[i] = (i * 13 + 1) & 0xFF
    struct.pack_into("<I", img, sb.SENSOR_SIZE_WORD, size - 32)
    t = struct.pack("<IHHIIII", sb.SENSOR_TRAILER_MAGIC, 1, hw, fw, size - 32, sb.SENSOR_LOAD, 1 | 1 << 8)
    img[size - 32:size - 4] = t + bytes(28 - len(t))
    struct.pack_into("<I", img, size - 4, zlib.crc32(bytes(img[:size - 4])) & 0xFFFFFFFF)
    return bytes(img)


def write_key(path):
    key = ec.generate_private_key(ec.SECP256R1())
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    return key


def c_array(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    img = sensor_image()
    with tempfile.TemporaryDirectory() as tmp:
        os.chmod(tmp, 0o700)
        ka = os.path.join(tmp, "a.pem")
        key_a = write_key(ka)
        key_b = ec.generate_private_key(ec.SECP256R1())
        src, dst = os.path.join(tmp, "img.bin"), os.path.join(tmp, "img.signed")
        with open(src, "wb") as f:
            f.write(img)
        subprocess.run([sys.executable, os.path.join(TOOLS, "explora_sign.py"), "sign", "--kind", "sensor",
                        "--key", ka, src, dst], check=True, stdout=subprocess.DEVNULL)
        with open(dst, "rb") as f:
            signed = f.read()
    assert signed[:len(img)] == img and len(signed) == len(img) + sb.SIZE
    ida = sb.key_id(key_a.public_key())
    tampered = bytearray(img)
    tampered[600] ^= 0x01  # same length, other content
    blocks = {
        "BLOCK_WRONG_HW": sb.build_block(sb.KIND_SENSOR, 0x0004, FW, img, key_a),
        "BLOCK_WRONG_VERSION": sb.build_block(sb.KIND_SENSOR, HW, FW + 1, img, key_a),
        "BLOCK_WRONG_KIND": sb.build_block(sb.KIND_GATEWAY, HW, FW, img, key_a),
        "BLOCK_WRONG_LENGTH": sb.build_block(sb.KIND_SENSOR, HW, FW, img + b"\0" * 8, key_a),
        "BLOCK_WRONG_HASH": sb.build_block(sb.KIND_SENSOR, HW, FW, bytes(tampered), key_a),
        "BLOCK_BAD_SIG": sb.build_block(sb.KIND_SENSOR, HW, FW, img, key_b, claimed_key_id=ida),
        "BLOCK_OTHER_KEY": sb.build_block(sb.KIND_SENSOR, HW, FW, img, key_b),
    }
    text = (
        "// Generated by gen_fixtures.py - do not edit. TEST keys only (private\n"
        "// parts were discarded); never a release key.\n#pragma once\n#include <cstdint>\n\n"
        f"static const uint32_t TEST_KEY_ID = 0x{ida:08X}u;\n"
        f"static const uint32_t OTHER_KEY_ID = 0x{sb.key_id(key_b.public_key()):08X}u;\n"
        + c_array("TEST_KEY_POINT", sb.public_point(key_a.public_key()))
        + "// Sensor image HW 0x0003 0.2.12 (synthetic) + its block, signed with the test key by explora_sign.py\n"
        + c_array("SIGNED_FILE", signed)
    )
    for name, block in blocks.items():
        text += c_array(name, block)
    with open(os.path.join(HERE, "fixtures.h"), "w") as f:
        f.write(text)
    print("fixtures.h written")


if __name__ == "__main__":
    main()
