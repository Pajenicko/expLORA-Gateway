#!/usr/bin/env python3
"""
Generates fixtures.h for test_partition_table: the partition tables of the
committed CSV files as ESP-IDF's gen_esp32part.py writes them (the Lite v1
and v2 layouts, the Pro). The test checks that PartitionTable.h recognises
exactly these and builds the v2 table byte for byte.

  python3 test/test_partition_table/gen_fixtures.py [path/to/gen_esp32part.py]
"""

import glob
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
TABLES = [
    ("LITE_V1_BIN", "partitions/huge_app_littlefs.csv"),
    ("LITE_V2_BIN", "partitions/lite_8MB_v2.csv"),
    ("PRO_BIN", "partitions/pro_16MB.csv"),
]


def tool():
    if len(sys.argv) > 1:
        return sys.argv[1]
    found = glob.glob(os.path.expanduser(
        "~/.platformio/packages/framework-arduinoespressif32/tools/gen_esp32part.py"))
    if not found:
        raise SystemExit("gen_esp32part.py not found - pass its path")
    return found[0]


def main():
    gen = tool()
    out = ["// Generated by gen_esp32part.py from the CSV files (gen_fixtures.py) - do not edit",
           "#pragma once", "#include <stdint.h>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name, csv in TABLES:
            dst = os.path.join(tmp, name + ".bin")
            subprocess.run([sys.executable, gen, "-q", os.path.join(ROOT, csv), dst], check=True)
            data = open(dst, "rb").read()
            if len(data) != 0xC00:
                raise SystemExit(f"{csv}: unexpected length {len(data)}")
            out.append(f"// {csv}")
            out.append(f"static const uint8_t {name}[{len(data)}] = {{")
            for i in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            out.append("};")
            out.append("")
    with open(os.path.join(HERE, "fixtures.h"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
